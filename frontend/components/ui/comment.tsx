import { Fragment } from 'react';
import { cn } from '@/lib/utils';

interface CommentProps {
  /**
   * The sentences, one to a line, in the voice: short, lowercase as written (nothing here changes
   * their case), the last one on what the chain did. Numbers in them come from fetched data.
   */
  lines: readonly string[];
  /** `lg`: the 404 verse's display size (21 px, the boards' `.comment-lg`); else 14 px. */
  size?: 'body' | 'lg';
  /** A note beside data is a paragraph; the 404 verse is the page's title. */
  as?: 'div' | 'h1';
  className?: string;
}

/**
 * A comment line (rubbing × Song print, phase 4): the ghost `#` (generated by `.comment::before`,
 * with empty alternative text, so it is never read out), then the lines in Courier Prime in the dim
 * ink. Prose, so no role; a reader hears the sentences in order (a space between the lines, so
 * they are not run together, which the line breaks do not show on screen).
 */
export function Comment({ lines, size = 'body', as: Tag = 'div', className }: CommentProps) {
  if (lines.length === 0) throw new Error('Comment: a comment has at least one line');
  const blank = lines.findIndex((line) => line.trim() === '');
  if (blank !== -1) throw new Error(`Comment: line ${blank + 1} is blank`);
  const body = lines.map((line, i) => (
    <Fragment key={i}>
      {i > 0 && ' '}
      <span data-comment-line="" className="block">
        {line}
      </span>
    </Fragment>
  ));
  return (
    <Tag className={cn('comment', size === 'lg' && 'comment-lg', className)}>
      {Tag === 'h1' ? <span>{body}</span> : <p>{body}</p>}
    </Tag>
  );
}
